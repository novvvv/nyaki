import type { Pack, PackWord } from "@/lib/packs";

/**
 * JLPT N5 수준 한자 — 주제별 6개 팩, 103자.
 *
 * JLPT는 2010년부터 공식 한자 목록을 내지 않는다. 흔히 쓰는 N5 목록(옛 4급 기준)을
 * 따랐고, 모두 상용한자(문화청 고시)에 들어 있다. 음독은 가타카나, 훈독은
 * 히라가나(괄호 안은 오쿠리가나). 훈음은 한국 한자음 기준이다.
 *
 * 카드에는 이렇게 담긴다 — 단어: 한자 / 의미: 훈음 / 발음: 음독 · 훈독 /
 * 예문: 예시 단어 / 예문 뜻: 예시 단어의 뜻.
 */

const UPDATED = "2026-11-26";

function k(
  term: string,
  meaning: string,
  reading: string,
  example: string,
  exampleMeaning: string,
): PackWord {
  return { term, meaning, reading, example, exampleMeaning, level: "N5" };
}

function pack(
  id: string,
  title: string,
  about: string,
  words: PackWord[],
): Pack {
  return {
    id: `jlpt-n5-kanji-${id}`,
    title: `N5 한자 ${title}`,
    source: "상용한자 · JLPT N5 수준",
    tags: ["일본어", "JLPT", "한자"],
    updatedAt: UPDATED,
    description: `${about} 훈음 · 음독 · 훈독과 예시 단어까지 카드에 담겨요.`,
    face: { label: "KANJI", glyph: words[0]?.term },
    words,
  };
}

